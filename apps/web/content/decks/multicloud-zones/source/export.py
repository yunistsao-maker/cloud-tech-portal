"""Build ../deck.json (topics, checklist, sources) from the topic sources.

The diagrams are generated by the helpers in lib.py, so edit the topic files,
then run from this folder:

    python3 export.py

Listing text, the cover and the appendix intro live in ../meta.json and are edited by hand.
The portal reads both files (apps/web/lib/decks.ts); nothing here runs at build time.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from lib import esc  # noqa: E402
from topics_a import TOPICS_A  # noqa: E402
from topics_b import CHECKLIST, SOURCES, TOPICS_B  # noqa: E402

META = json.load(open(os.path.join(HERE, '..', 'meta.json'), encoding='utf-8'))
BASE = f"/reports/{META['slug']}/"
OUT = os.path.join(HERE, '..', 'deck.json')
ZONE = {'z-ext': 'ext', 'z-dmz': 'dmz', 'z-int': 'int', 'z-mgmt': 'mgmt', 'z-peer': 'peer'}


def scoped_svg(t):
    """Prefix marker ids per topic: several diagrams can share one page (cover grid)."""
    s = t['svg']()
    pre = f"mcz{t['num']}-"
    s = re.sub(r'id="(ah[\w-]*)"', lambda m: f'id="{pre}{m.group(1)}"', s)
    s = re.sub(r'url\(#(ah[\w-]*)\)', lambda m: f'url(#{pre}{m.group(1)})', s)
    return s.replace('<svg class="dg"', f'<svg class="dg" aria-label="{esc(t["title"])}"', 1)


def portal_links(html):
    """Deck-relative links (../05-x/diagram.html) become portal routes; external links open a new tab."""
    def internal(m):
        slug, view, frag = m.group(1), m.group(2), m.group(3) or ''
        return f'href="{BASE}{slug}/{"deep-dive/" if view == "deep-dive" else ""}{frag}"'
    html = re.sub(r'href="\.\./([a-z0-9-]+)/(diagram|deep-dive)\.html(#[\w-]+)?"', internal, html)
    return re.sub(r'<a href="(https?://[^"]+)"(?![^>]*target=)', r'<a href="\1" target="_blank" rel="noreferrer"', html)


def topic(t):
    deep = portal_links(t['deep'].strip())
    sections = [{'id': i, 'title': re.sub(r'<[^>]+>', '', x)} for i, x in re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', deep)]
    return {
        'num': t['num'], 'slug': t['slug'], 'title': t['title'], 'short': t['short'],
        'lede': t['lede'], 'zones': t['zones'], 'caption': t['caption'], 'svg': scoped_svg(t),
        'services': {c: [{'name': n, 'note': d} for n, d in t['services'][c]] for c in ('aws', 'azure', 'gcp')},
        'summary': t['summary'], 'deepLede': t['deep_lede'], 'deepHtml': deep, 'sections': sections,
    }


deck = {
    'topics': [topic(t) for t in TOPICS_A + TOPICS_B],
    'checklist': [{'zone': ZONE[z], 'tag': tag, 'text': s} for z, tag, s in CHECKLIST],
    'sources': [{'url': u, 'name': n, 'note': d} for u, n, d in SOURCES],
}

with open(OUT, 'w', encoding='utf-8') as f:
    json.dump(deck, f, ensure_ascii=False, indent=1)
    f.write('\n')
print(f"wrote {os.path.relpath(OUT)}: {len(deck['topics'])} topics")
