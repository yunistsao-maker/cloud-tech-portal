import { z } from "zod";

/** Trust zones; each has a colour used in chips, diagrams and the checklist. */
export const ZONES = ["ext", "dmz", "int", "mgmt", "peer"] as const;
export type Zone = (typeof ZONES)[number];
export const CLOUDS = ["aws", "azure", "gcp"] as const;
export type Cloud = (typeof CLOUDS)[number];

const Service = z.object({ name: z.string(), note: z.string() });

const Topic = z.object({
  num: z.string().regex(/^\d{2}$/),
  slug: z.string().regex(/^[a-z0-9-]+$/),
  title: z.string(),
  /** Short label for the pager and table of contents. */
  short: z.string(),
  lede: z.string(),
  zones: z.array(z.enum(ZONES)),
  caption: z.string(),
  /** Diagram markup generated by the deck source; text that varies by cloud carries c-aws / c-azure / c-gcp. */
  svg: z.string(),
  services: z.object({ aws: z.array(Service), azure: z.array(Service), gcp: z.array(Service) }),
  summary: z.array(z.string()),
  deepLede: z.string(),
  deepHtml: z.string(),
  /** The deep dive's h2 anchors, in order. */
  sections: z.array(z.object({ id: z.string(), title: z.string() })),
});
export type DeckTopic = z.infer<typeof Topic>;

/** Hand-edited: listing fields (same shape as a report's), the cover and the appendix intro. */
export const DeckMeta = z.object({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  title: z.string(),
  summary: z.object({ en: z.string(), zh: z.string() }),
  author: z.string(),
  publishedAt: z.string().date(),
  updatedAt: z.string().date().optional(),
  lang: z.string(),
  categories: z.array(z.string()),
  capabilities: z.array(z.string()),
  /** The published original of the deck. */
  sourceUrl: z.string().url(),
  cover: z.object({ eyebrow: z.string(), lede: z.string(), thesis: z.string() }),
  appendix: z.object({ slug: z.string().regex(/^[a-z0-9-]+$/), title: z.string(), lede: z.string(), note: z.string() }),
});
export type DeckMeta = z.infer<typeof DeckMeta>;

/** Generated by content/decks/<slug>/source/export.py. */
export const DeckBody = z.object({
  topics: z.array(Topic).min(1),
  checklist: z.array(z.object({ zone: z.enum(ZONES), tag: z.string(), text: z.string() })),
  sources: z.array(z.object({ url: z.string().url(), name: z.string(), note: z.string() })),
});
export type DeckBody = z.infer<typeof DeckBody>;

export type Deck = DeckMeta & DeckBody;
